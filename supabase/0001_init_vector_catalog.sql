-- 1. Enable the pgvector extension for high-performance vector operations
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Create the core E-Commerce Product Catalog Table
CREATE TABLE IF NOT EXISTS public.products (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title       TEXT NOT NULL,
    description TEXT NOT NULL,
    category    TEXT NOT NULL,
    price       NUMERIC(10, 2) NOT NULL,
    image_url   TEXT NOT NULL,
    in_stock    BOOLEAN NOT NULL DEFAULT true,
    -- 768-dimensional vector embedding generated by Google Vertex AI
    embedding   vector(768),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create HNSW Index for ultra-low latency (<15ms) cosine similarity search
-- HNSW provides sub-linear search time over traditional IVFFlat indexes without requiring pre-training.
CREATE INDEX IF NOT EXISTS idx_products_embedding_hnsw 
ON public.products 
USING hnsw (embedding vector_cosine_ops)
WITH (m = 16, ef_construction = 64);

-- 4. Create B-Tree Indexes for fast scalar queries and hybrid search filters
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);
CREATE INDEX IF NOT EXISTS idx_products_title_trgm ON public.products USING gin (title gin_trgm_ops);

-- =============================================================================
-- STORED PROCEDURE / RPC: match_products
-- HOT PATH: Executed via REST/PostgREST from the Go backend.
-- Calculates cosine distance (1 - cosine similarity) and returns ranked results.
-- =============================================================================
CREATE OR REPLACE FUNCTION public.match_products(
    query_embedding vector(768),
    match_threshold FLOAT DEFAULT 0.3,
    match_count INT DEFAULT 12
)
RETURNS TABLE (
    id UUID,
    title TEXT,
    description TEXT,
    category TEXT,
    price NUMERIC,
    image_url TEXT,
    in_stock BOOLEAN,
    similarity FLOAT
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT
        p.id,
        p.title,
        p.description,
        p.category,
        p.price,
        p.image_url,
        p.in_stock,
        -- Cosine similarity formula: 1 - cosine distance
        (1 - (p.embedding <=> query_embedding))::FLOAT AS similarity
    FROM public.products p
    WHERE p.in_stock = true
      AND (1 - (p.embedding <=> query_embedding)) > match_threshold
    ORDER BY p.embedding <=> query_embedding ASC
    LIMIT match_count;
END;
$$;

